User = get_user_model()


class ContentModelTests(TestCase):
    def setUp(self):
        self.user = User.objects.create_user(
            username="autor_test",
            password="Password123!",
            email="autor@test.com",
            must_change_password=False,
        )

    def test_slug_autogenerated_from_titulo(self):
        contenido = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Nueva Jornada de Hidrogeología 2026",
            resumen="Resumen breve",
            cuerpo="<p>Texto completo</p>",
            creado_por=self.user,
        )
        self.assertEqual(contenido.slug, "nueva-jornada-de-hidrogeologia-2026")

    def test_slug_uniqueness_with_counter(self):
        c1 = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Congreso Minero",
            resumen="Resumen 1",
            cuerpo="<p>Texto 1</p>",
            creado_por=self.user,
        )
        c2 = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Congreso Minero",
            resumen="Resumen 2",
            cuerpo="<p>Texto 2</p>",
            creado_por=self.user,
        )
        self.assertEqual(c1.slug, "congreso-minero")
        self.assertEqual(c2.slug, "congreso-minero-1")

    def test_estado_automatico_sin_fecha_es_borrador(self):
        contenido = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Borrador inicial",
            resumen="Resumen",
            cuerpo="<p>Borrador</p>",
            fecha_publicacion=None,
            creado_por=self.user,
        )
        self.assertEqual(contenido.estado_publicacion, Contenido.EstadoPublicacion.BORRADOR)
        self.assertFalse(contenido.esta_publicado)

    def test_estado_automatico_fecha_futura_es_programado(self):
        futuro = timezone.now() + timedelta(days=5)
        contenido = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Noticia a futuro",
            resumen="Resumen",
            cuerpo="<p>Futuro</p>",
            fecha_publicacion=futuro,
            creado_por=self.user,
        )
        self.assertEqual(contenido.estado_publicacion, Contenido.EstadoPublicacion.PROGRAMADO)
        self.assertFalse(contenido.esta_publicado)

    def test_estado_automatico_fecha_pasada_o_actual_es_publicado(self):
        ahora = timezone.now() - timedelta(minutes=10)
        contenido = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Noticia publicada",
            resumen="Resumen",
            cuerpo="<p>Publicado</p>",
            fecha_publicacion=ahora,
            creado_por=self.user,
        )
        self.assertEqual(contenido.estado_publicacion, Contenido.EstadoPublicacion.PUBLICADO)
        self.assertTrue(contenido.esta_publicado)

    def test_sanitizer_removes_dangerous_tags_and_handlers(self):
        html_input = (
            "<p>Parrafo normal con <strong>negrita</strong>.</p>"
            "<script>alert('ataque');</script>"
            "<iframe src='http://malicioso.com'></iframe>"
            "<a href='javascript:alert(1)' onclick='evil()'>Enlace malicioso</a>"
        )
        clean = sanitize_html(html_input)
        self.assertNotIn("<script>", clean)
        self.assertNotIn("alert('ataque')", clean)
        self.assertNotIn("<iframe>", clean)
        self.assertNotIn("onclick", clean)
        self.assertNotIn("javascript:", clean)
        self.assertIn("<p>Parrafo normal con <strong>negrita</strong>.</p>", clean)

    def test_model_save_applies_sanitization(self):
        contenido = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Prueba de sanitización en modelo",
            resumen="Resumen",
            cuerpo="<p>Texto con <script>alert('xss');</script> script.</p>",
            creado_por=self.user,
        )
        self.assertNotIn("<script>", contenido.cuerpo)
        self.assertIn("<p>Texto con  script.</p>", contenido.cuerpo)


class ContentViewPermissionsAndAccessTests(TestCase):
    def setUp(self):
        # Crear grupos
        self.grupo_colaboradores = Group.objects.create(name="colaboradores")
        self.grupo_matriculados = Group.objects.create(name="matriculados")

        # Usuarios
        self.colaborador = User.objects.create_user(
            username="colaborador",
            password="Password123!",
            email="colaborador@test.com",
            must_change_password=False,
        )
        self.colaborador.groups.add(self.grupo_colaboradores)

        self.matriculado = User.objects.create_user(
            username="matriculado",
            password="Password123!",
            email="matriculado@test.com",
            must_change_password=False,
        )
        self.matriculado.groups.add(self.grupo_matriculados)

        self.usuario_comun = User.objects.create_user(
            username="visitante_registrado",
            password="Password123!",
            email="visitante@test.com",
            must_change_password=False,
        )

        # Publicaciones con distintas visibilidades
        ahora = timezone.now() - timedelta(hours=1)

        self.noticia_publica = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Noticia Pública",
            resumen="Resumen público",
            cuerpo="<p>Visible para todos</p>",
            visibilidad=Contenido.Visibilidad.PUBLICO,
            fecha_publicacion=ahora,
            creado_por=self.colaborador,
        )

        self.noticia_matriculados = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Noticia Exclusiva Matriculados",
            resumen="Resumen matriculados",
            cuerpo="<p>Solo logueados</p>",
            visibilidad=Contenido.Visibilidad.MATRICULADOS,
            fecha_publicacion=ahora,
            creado_por=self.colaborador,
        )

        self.noticia_interna = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Noticia Interna",
            resumen="Resumen interno",
            cuerpo="<p>Solo colaboradores y admin</p>",
            visibilidad=Contenido.Visibilidad.INTERNO,
            fecha_publicacion=ahora,
            creado_por=self.colaborador,
        )

        self.noticia_borrador = Contenido.objects.create(
            tipo=Contenido.Tipo.NOTICIA,
            titulo="Noticia en Borrador",
            resumen="Resumen borrador",
            cuerpo="<p>En preparación</p>",
            visibilidad=Contenido.Visibilidad.PUBLICO,
            fecha_publicacion=None,
            creado_por=self.colaborador,
        )

    def test_public_user_only_sees_published_and_public_content(self):
        response = self.client.get(reverse("content:novedades_list"))
        self.assertEqual(response.status_code, 200)

        titulos = [c.titulo for c in response.context["novedades"]]
        self.assertIn("Noticia Pública", titulos)
        self.assertNotIn("Noticia Exclusiva Matriculados", titulos)
        self.assertNotIn("Noticia Interna", titulos)
        self.assertNotIn("Noticia en Borrador", titulos)

    def test_authenticated_user_sees_matriculados_content_too(self):
        self.client.force_login(self.matriculado)
        response = self.client.get(reverse("content:novedades_list"))
        self.assertEqual(response.status_code, 200)

        titulos = [c.titulo for c in response.context["novedades"]]
        self.assertIn("Noticia Pública", titulos)
        self.assertIn("Noticia Exclusiva Matriculados", titulos)
        self.assertNotIn("Noticia Interna", titulos)
        self.assertNotIn("Noticia en Borrador", titulos)

    def test_staff_user_sees_all_visibilities_on_public_list(self):
        self.client.force_login(self.colaborador)
        response = self.client.get(reverse("content:novedades_list"))
        self.assertEqual(response.status_code, 200)

        titulos = [c.titulo for c in response.context["novedades"]]
        self.assertIn("Noticia Pública", titulos)
        self.assertIn("Noticia Exclusiva Matriculados", titulos)
        self.assertIn("Noticia Interna", titulos)
        # Los borradores siguen sin verse en la lista pública
        self.assertNotIn("Noticia en Borrador", titulos)

    def test_borrador_never_accessible_in_public_detail_for_regular_user(self):
        response = self.client.get(
            reverse("content:novedad_detail", kwargs={"slug": self.noticia_borrador.slug})
        )
        self.assertEqual(response.status_code, 404)

    def test_anonymous_user_cannot_access_create_content(self):
        response = self.client.get(reverse("content:contenido_create"))
        self.assertEqual(response.status_code, 302)  # Redirección de login

    def test_matriculado_without_content_permissions_cannot_access_create(self):
        self.client.force_login(self.matriculado)
        response = self.client.get(reverse("content:contenido_create"))
        # handle_no_permission redirige al dashboard
        self.assertEqual(response.status_code, 302)
        self.assertRedirects(response, reverse("accounts:dashboard"))

    def test_colaborador_can_access_and_create_content(self):
        self.client.force_login(self.colaborador)
        response = self.client.get(reverse("content:contenido_create"))
        self.assertEqual(response.status_code, 200)

        post_data = {
            "tipo": Contenido.Tipo.NOTICIA,
            "titulo": "Noticia Creada por Colaborador",
            "resumen": "Resumen de prueba",
            "cuerpo": "<p>Cuerpo de prueba</p>",
            "visibilidad": Contenido.Visibilidad.PUBLICO,
            "fecha_publicacion": timezone.now().strftime("%Y-%m-%dT%H:%M"),
        }
        post_response = self.client.post(reverse("content:contenido_create"), post_data)
        self.assertEqual(post_response.status_code, 302)

        creado = Contenido.objects.filter(titulo="Noticia Creada por Colaborador").first()
        self.assertIsNotNone(creado)
        self.assertEqual(creado.creado_por, self.colaborador)

    def test_toggle_estado_switches_between_publicado_and_borrador(self):
        self.client.force_login(self.colaborador)
        self.assertEqual(self.noticia_publica.estado_publicacion, Contenido.EstadoPublicacion.PUBLICADO)

        # Toggle a borrador
        toggle_url = reverse("content:contenido_toggle_estado", kwargs={"pk": self.noticia_publica.pk})
        self.client.post(toggle_url)

        self.noticia_publica.refresh_from_db()
        self.assertEqual(self.noticia_publica.estado_publicacion, Contenido.EstadoPublicacion.BORRADOR)
        self.assertIsNone(self.noticia_publica.fecha_publicacion)

        # Toggle de nuevo a publicado
        self.client.post(toggle_url)
        self.noticia_publica.refresh_from_db()
        self.assertEqual(self.noticia_publica.estado_publicacion, Contenido.EstadoPublicacion.PUBLICADO)
        self.assertIsNotNone(self.noticia_publica.fecha_publicacion)

